"""Independent deterministic fixture authoring. Does NOT import the decoder.

Only writes checked-in host fixtures, never a device. Expected JSON is constructed
from the logical cases rather than obtained by decoding the generated bytes.
"""
from pathlib import Path
import hashlib
import json
import struct
import zlib

HERE = Path(__file__).resolve().parent / "fixtures"
MAX64 = (1 << 64) - 1


def pack(fmt, *values):
    return struct.pack("<" + fmt, *values)


def seal(page, committed=True):
    page[248:252] = pack("I", zlib.crc32(page[:248]))
    page[252:256] = pack("I", 0xC0DEC0DE if committed else 0xFFFFFFFF)
    return bytes(page)


def page(magic, sid, seq, count, payload):
    assert len(payload) <= 232
    result = bytearray(b"\xff" * 256)
    result[:16] = magic + pack("IIHH", sid, seq, count, len(payload))
    result[16:16 + len(payload)] = payload
    return seal(result)


def metadata(start=4294967200):
    return dict(format_major=2, format_minor=0, session_start_us=start,
                device_id_hex=bytes(range(1, 9)).hex(), session_uuid_hex=bytes(range(16)).hex(),
                firmware_sha256=bytes(range(32)).hex(), boot_uuid_hex=bytes(range(32, 48)).hex(),
                imu_rate_millihz=100000, imu_odr_millihz=104000, accel_ug_per_lsb=61,
                gyro_udps_per_lsb=8750, accel_range_mg=2000, gyro_range_mdps=245000,
                gps_period_us=100000, gga_epoch_divisor=10, uart_baud=38400,
                required_features=31, gps_profile_checked_us=1000000, gps_profile_state=1,
                timestamp_basis=1, calibration=0, axis_convention=1,
                imu_model="LSM6DS3TR-C", gps_model="MAX-M10S", gps_firmware="SPG 5.10", extensions=[])


def header(sid=2, seq=0, sector_index=0, start=4294967200):
    payload = bytearray(196)
    payload[:16] = pack("HHIQ", 2, 0, sector_index, start)
    payload[16:24] = bytes(range(1, 9))
    payload[24:40] = bytes(range(16))
    payload[40:72] = bytes(range(32))
    payload[72:88] = bytes(range(32, 48))
    payload[88:128] = pack("10I", 100000, 104000, 61, 8750, 2000, 245000, 100000, 10, 38400, 31)
    payload[128:140] = pack("Q4B", 1000000, 1, 1, 0, 1)
    for at, value in ((140, b"LSM6DS3TR-C"), (156, b"MAX-M10S"), (172, b"SPG 5.10")):
        payload[at:at + 16] = value.ljust(16, b"\0")
    return page(b"TPH2", sid, seq, 0, payload)


def record(kind, timestamp, payload):
    return pack("BBHQ", kind, 1, 12 + len(payload), timestamp) + payload


def imu(timestamp, axes):
    raw = record(1, timestamp, pack("6h", *axes))
    return raw, dict(type="IMU_RAW", type_id=1, schema_version=1,
                     timestamp_us=timestamp, axes_raw=list(axes))


def rmc(timestamp, valid=True):
    # Void observation deliberately retains reported coordinates, but must
    # never become a usable position/speed/course in host output.
    flags = 127 if valid else 125
    raw = record(2, timestamp, pack("IiiIIIIBB2s", flags, 507752560, -900030,
                                    1234, 35999999, 20261030, 58460000,
                                    ord("A") if valid else ord("V"), ord("A"), b"GN"))
    expected = dict(type="GPS_RMC", type_id=2, schema_version=1, timestamp_us=timestamp,
                    validity_mask=flags, receiver_status="A" if valid else "V", mode="A", talker="GN",
                    utc=dict(date="2026-10-30", time_of_day_ms=58460000), fix_valid=valid,
                    fields=dict(latitude_e7=507752560, longitude_e7=-900030,
                                speed_mm_s=1234, course_e5_deg=35999999),
                    position=dict(latitude_deg=50.775256, longitude_deg=-0.090003) if valid else None,
                    speed_m_s=1.234 if valid else None, course_deg=359.99999 if valid else None)
    return raw, expected


def gga(timestamp):
    raw = record(3, timestamp, pack("IIIiiHHB2sB", 63, 20261030, 58460000,
                                   -1200, 45000, 128, 7, 1, b"GN", 0))
    return raw, dict(type="GPS_GGA_QUALITY", type_id=3, schema_version=1,
                     timestamp_us=timestamp, validity_mask=63,
                     utc=dict(date="2026-10-30", time_of_day_ms=58460000),
                     date_is_associated=True, fix_quality=1, talker="GN",
                     altitude_msl_mm=-1200, geoid_separation_mm=45000, hdop=1.28, satellites_used=7)


def event(timestamp):
    raw = record(4, timestamp, pack("HBBIIQ", 5, 1, 2, 7, 1, 18446744073709551614))
    return raw, dict(type="EVENT", type_id=4, schema_version=1, timestamp_us=timestamp,
                     code=5, severity=1, stream=2, argument=7, count=1, detail=18446744073709551614)


def data(records, sid=2, seq=0):
    return page(b"TPD2", sid, seq, len(records), b"".join(r[0] for r in records))


def footer(records, sid=2, seq=1, stop=None):
    stop = records[-1][1]["timestamp_us"] + 100 if stop is None and records else stop
    counts = [sum(r[1]["type_id"] == kind for r in records) for kind in range(1, 5)]
    first = records[0][1]["timestamp_us"] if records else MAX64
    last = records[-1][1]["timestamp_us"] if records else MAX64
    invalid = sum(r[1]["type_id"] == 2 and not r[1]["fix_valid"] for r in records)
    payload = pack("QII4Q4Q5Q", stop, 0, 0, *counts, 0, 0, 0, 0, 0, 0, invalid, first, last)
    expected = dict(stop_us=stop, close_reason=0, flags=0, committed_by_type=counts,
                    dropped_by_type=[0, 0, 0, 0], missed_imu_intervals=0,
                    gps_checksum_failures=0, invalid_rmc_observations=invalid,
                    first_record_us=None if first == MAX64 else first,
                    last_record_us=None if last == MAX64 else last)
    return page(b"TPE2", sid, seq, 0, payload), expected


def sector(header_page, pages, footer_page=None):
    output = bytearray(b"\xff" * 4096)
    output[:256] = header_page
    for index, value in enumerate(pages, 1):
        output[index * 256:(index + 1) * 256] = value
    if footer_page:
        output[3840:] = footer_page
    return bytes(output)


def v1():
    def legacy(magic, sequence, count, payload):
        p = bytearray(b"\xff" * 256)
        p[:16] = magic + pack("III", 1, sequence, count)
        p[16:16 + len(payload)] = payload
        return seal(p)
    axes = [1, -2, 32767, -32768, 0, 100]
    samples = [(0xFFFFFFF0, axes), (0x10, axes)]
    h = legacy(b"TPH1", 0, 0, pack("5I", 1, 100, 61, 8750, 0xFFFFFF00))
    d = legacy(b"TPD1", 0, 2, b"".join(pack("I6h", ms, *a) for ms, a in samples))
    f = legacy(b"TPE1", 1, 2, pack("II", 0, 0))
    expected = dict(version=1, session_id=1, metadata=dict(format_major=1, format_minor=0,
                    imu_rate_millihz=100000, accel_ug_per_lsb=61, gyro_udps_per_lsb=8750,
                    session_start_ms=0xFFFFFF00), sectors=[0], status="closed",
                    records=[dict(type="IMU_RAW", type_id=1, schema_version=0,
                                  timestamp_ms=ms, axes_raw=a) for ms, a in samples],
                    footer=dict(committed_samples=2, dropped_samples=0, missed_deadlines=0))
    return sector(h, [d], f), expected


def result(sessions, issues=None):
    return dict(schema="tacticpod.decode/1", sessions=sessions, issues=issues or [])


def session(records, footer_value=None, sectors=None, start=4294967200, status="closed"):
    return dict(version=2, session_id=2, metadata=metadata(start), sectors=sectors or [0],
                records=[r[1] for r in records], footer=footer_value, status=status)


def fixtures():
    old, old_expected = v1()
    first = [imu(4294967290, (0, 0, 0, -1, 1, 2)), rmc(4294967300), gga(4294967310)]
    second = [rmc(4295067300, False), event(4295067310)]
    all_records = first + second
    f, f_expected = footer(all_records, seq=2)
    mixed = old + sector(header(), [data(first)]) + sector(header(seq=1, sector_index=1), [data(second, seq=1)], f)
    mixed_expected = result([old_expected, session(all_records, f_expected, [4096, 8192])])
    yield "mixed_v1_v2", mixed, mixed_expected
    # Both sides of the 32-bit microsecond rollover are in mixed_v1_v2.
    # This separate fixture crosses 32-bit MILLIS while retaining 64-bit us.
    large = [imu(4294967295000, (-32768, 32767, 1, 2, 3, 4)), imu(4294967297000, (1, 2, 3, 4, 5, 6))]
    f, fe = footer(large)
    yield "timestamp_rollover", sector(header(), [data(large)], f), result([session(large, fe)])
    kept = [imu(4294967290, (1, 2, 3, 4, 5, 6))]
    torn = bytearray(data([rmc(4294967300)], seq=1))
    torn[252:] = b"\xff" * 4
    incomplete = sector(header(), [data(kept), bytes(torn)])
    issues = [dict(offset=512, code="data_invalid", severity="warning", message="missing commit marker"),
              dict(offset=0, code="incomplete_session", severity="warning", message="no fully verifiable clean session end")]
    yield "interrupted", incomplete, result([session(kept, status="interrupted")], issues)
    broken = bytearray(data([rmc(4294967300)], seq=1))
    broken[48] ^= 1
    issues = [dict(offset=512, code="data_invalid", severity="error", message="CRC mismatch")]
    yield "corrupt_crc", sector(header(), [data(kept), bytes(broken)]), result([session(kept, status="damaged")], issues)
    # A void, entirely unavailable observation is still a timestamped loss-of-fix.
    raw = record(2, 4294967290, pack("IiiIIIIBB2s", 0, 0, 0, 0, 0, 0, 0, ord("V"), 0, b"GN"))
    absent = (raw, dict(type="GPS_RMC", type_id=2, schema_version=1, timestamp_us=4294967290,
              validity_mask=0, receiver_status="V", mode=None, talker="GN", utc=dict(date=None, time_of_day_ms=None),
              fix_valid=False, fields=dict(latitude_e7=None, longitude_e7=None, speed_mm_s=None, course_e5_deg=None),
              position=None, speed_m_s=None, course_deg=None))
    f, fe = footer([absent])
    yield "missing_gps", sector(header(), [data([absent])], f), result([session([absent], fe)])
    f, fe = footer([], seq=0, stop=4294967200)
    yield "empty_session", sector(header(), [], f), result([session([], fe)])


def generate():
    output = {}
    # Expected JSON contract independently represents every u64 as decimal text.
    u64 = {"timestamp_us", "session_start_us", "gps_profile_checked_us", "stop_us",
           "first_record_us", "last_record_us", "missed_imu_intervals",
           "gps_checksum_failures", "invalid_rmc_observations", "detail"}

    def json_expected(value):
        if isinstance(value, dict):
            return {key: ([str(n) for n in item] if key in ("committed_by_type", "dropped_by_type") else
                          str(item) if key in u64 and item is not None else json_expected(item))
                    for key, item in value.items()}
        if isinstance(value, list):
            return [json_expected(item) for item in value]
        return value

    for name, binary, decoded in fixtures():
        output[name + ".bin"] = binary
        output[name + ".expected.json"] = (json.dumps(json_expected(decoded), indent=2, sort_keys=True) + "\n").encode()
    manifest = {name: hashlib.sha256(content).hexdigest() for name, content in sorted(output.items())}
    output["sha256.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return output


if __name__ == "__main__":
    HERE.mkdir(parents=True, exist_ok=True)
    for name, content in generate().items():
        (HERE / name).write_bytes(content)
    print("Generated deterministic host-only fixtures in", HERE)
